package model

import "time"

// Message хранит сообщение в исходном бинарном виде.
// Value == nil означает tombstone; пустой срез, отличный от nil, — сообщение из нуля байт.
type Message struct {
	// Topic — имя топика, которому принадлежит сообщение.
	Topic string
	// Partition — номер партиции прочитанной записи; при публикации её выбирает брокерный адаптер.
	Partition int
	// Offset — позиция прочитанной записи внутри партиции, не глобальный номер сообщения.
	Offset int64
	// Time — временная метка записи, полученная из брокера.
	Time time.Time
	// Key — бинарный ключ; nil означает отсутствие ключа, пустой срез — ключ нулевой длины.
	Key []byte
	// Headers — упорядоченные заголовки; имена могут повторяться.
	Headers []Header
	// Value — бинарное тело; nil означает tombstone, пустой срез — сообщение из нуля байт.
	Value []byte
}

// Header хранит один заголовок сообщения независимо от формата его тела.
type Header struct {
	// Key — имя заголовка.
	Key string
	// Value — бинарное значение; nil и пустой срез сохраняются как разные значения.
	Value []byte
}
